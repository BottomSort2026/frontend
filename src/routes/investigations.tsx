import { useSuspenseQuery } from "@tanstack/react-query";
import { createFileRoute } from "@tanstack/react-router";
import { useEffect, useMemo, useRef, type ReactNode } from "react";
import { investigationsQuery, warmQuery } from "../api/queries";
import type { Habitat, Pillar } from "../api/types";
import { InvestigationDetail } from "../investigations/InvestigationDetail";
import { InvestigationRefs } from "../investigations/Refs";
import {
  coverageFor,
  HABITATS,
  HABITAT_NAME,
  listed,
  PILLARS,
  PILLAR_NAME,
  reportDate,
  shortName,
  type Investigation,
} from "../investigations/report";
import "../investigations/investigations.css";
import { Section, SectionBlock } from "../sections/Section";
import { ChevronLeft, Droplet, Sensor, Shield } from "../ui/icons";
import { Readout } from "../ui/Readout";
import { FilterTag, Tag } from "../ui/Tag";

interface InvestigationsSearch {
  /** Order the ranking for this habitat, and show its coverage. Default: all habitats. */
  habitat?: Habitat;
  pillar?: Pillar;
  /** The one investigation whose panel is open (its accession). */
  open?: string;
}

export const Route = createFileRoute("/investigations")({
  // Filters and the open investigation live in the URL, so a view can be shared as a link.
  validateSearch: (search: Record<string, unknown>): InvestigationsSearch => ({
    habitat: HABITATS.find((h) => h === search.habitat),
    pillar: PILLARS.find((p) => p === search.pillar),
    open: typeof search.open === "string" ? search.open : undefined,
  }),
  // Starts the download without waiting for it: the section opens at once and shows its
  // content when the report arrives.
  loader: ({ context }) => void warmQuery(context.queryClient, investigationsQuery),
  component: InvestigationsPage,
});

// What each pillar is. The investigations under it come from the report, never from here.
const PILLAR_INFO = {
  prevention: {
    icon: <Shield />,
    body: "Control ignition sources and choose materials that will not keep burning.",
  },
  detection: {
    icon: <Sensor />,
    body: "Notice a fire early, from the smoke and aerosols it really produces in microgravity.",
  },
  suppression: {
    icon: <Droplet />,
    body: "Put a flame out, for example by diluting the atmosphere around it.",
  },
} as const satisfies Record<Pillar, unknown>;

const rowId = (accession: string) => `inv-${accession}`;

function InvestigationsPage() {
  return (
    <Section
      id="investigations"
      title="Every investigation, ranked for fire safety."
      lead="NASA's combustion investigations in the Physical Sciences Informatics repository, read from the project's corpus and scored on five criteria. Every statement points to its source."
      loading="Loading the investigations report…"
      failed="The investigations report did not load."
    >
      <InvestigationsContent />
    </Section>
  );
}

/** Everything that reads the report. It suspends until the report is there. */
function InvestigationsContent() {
  const { habitat, pillar, open } = Route.useSearch();
  const navigate = Route.useNavigate();
  const { data: report } = useSuspenseQuery(investigationsQuery);

  const names = useMemo(
    () => new Map(report.investigations.map((i) => [i.accession, shortName(i)])),
    [report],
  );
  const shown = listed(report.investigations, { habitat, pillar });
  const setSearch = (next: InvestigationsSearch) =>
    void navigate({ search: (prev) => ({ ...prev, ...next }), replace: true });

  // Opening from a reference (a name in the overview, a pillar, a hardware group) may point far
  // down the page: the row is brought to the top and focused. Opening from the row itself only
  // keeps it in view, since closing the panel above can move it.
  const arrival = useRef<"start" | "nearest">("nearest");
  useEffect(() => {
    if (!open) return;
    const row = document.getElementById(rowId(open));
    row?.scrollIntoView({ block: arrival.current });
    if (arrival.current === "start") row?.querySelector("button")?.focus({ preventScroll: true });
    arrival.current = "nearest";
  }, [open]);

  const toggle = (accession: string) =>
    setSearch({ open: open === accession ? undefined : accession });
  /** From a reference: opens the investigation, dropping a pillar filter that would hide it. */
  const openFromRef = (accession: string) => {
    arrival.current = "start";
    const target = report.investigations.find((i) => i.accession === accession);
    setSearch({ open: accession, pillar: pillar && target?.pillars[pillar] ? pillar : undefined });
  };

  const { run, synthesis, rubric } = report;
  const top = habitat ? report.habitat_top[habitat] : undefined;

  return (
    <>
      <SectionBlock className="ff-inv-intro">
        <div className="ff-sec__row">
          <Tag variant="gap">Generated by Claude from the corpus</Tag>
          <Tag>Research results, not certification</Tag>
        </div>
        <p className="ff-note">
          {run.model} read each investigation's own passages on {reportDate(run.generated_at)} and
          scored it from 0 to {rubric.max_score} on each criterion, with reasons and sources. The
          totals, the ranking and the coverage below were computed from those scores.
        </p>
        <p className="ff-inv-overview">{synthesis.overview.text}</p>
        <InvestigationRefs
          accessions={synthesis.overview.accessions}
          names={names}
          onOpen={openFromRef}
        />
      </SectionBlock>

      <SectionBlock className="ff-sec__head">
        <p className="ff-eyebrow">Prevention, detection, suppression</p>
        <span role="group" aria-label="Habitat" className="ff-sec__row">
          <FilterTag pressed={!habitat} onPress={() => setSearch({ habitat: undefined })}>
            All habitats
          </FilterTag>
          {HABITATS.map((h) => (
            <FilterTag key={h} pressed={habitat === h} onPress={() => setSearch({ habitat: h })}>
              {HABITAT_NAME[h]}
            </FilterTag>
          ))}
        </span>
        {top?.length ? (
          <p className="ff-note">
            Most relevant for {HABITAT_NAME[habitat!]}:{" "}
            <InvestigationRefs
              accessions={top.map((t) => t.accession)}
              names={names}
              onOpen={openFromRef}
            />
          </p>
        ) : null}
      </SectionBlock>
      <SectionBlock className="ff-pillars">
        {PILLARS.map((p, i) => {
          const covered = coverageFor(report, p, habitat);
          return (
            <article className="ff-pillar" key={p}>
              <div className="ff-pillar__head">
                <span className="ff-eyebrow">0{i + 1}</span>
                {PILLAR_INFO[p].icon}
              </div>
              <h3 className="ff-pillar__title">{PILLAR_NAME[p]}</h3>
              <p className="ff-pillar__body">{PILLAR_INFO[p].body}</p>
              <div className="ff-pillar__meta">
                <span className="ff-eyebrow">
                  {covered.length} {covered.length === 1 ? "investigation" : "investigations"}
                  {habitat ? ` for ${HABITAT_NAME[habitat]}` : ""}
                </span>
                {covered.length > 0 ? (
                  <InvestigationRefs accessions={covered} names={names} onOpen={openFromRef} />
                ) : (
                  <p className="ff-note">No investigation covers it for this habitat.</p>
                )}
              </div>
            </article>
          );
        })}
      </SectionBlock>

      <SectionBlock className="ff-sec__head">
        <p className="ff-eyebrow">Ranking</p>
        <span role="group" aria-label="Filter by pillar" className="ff-sec__row">
          <FilterTag pressed={!pillar} onPress={() => setSearch({ pillar: undefined })}>
            All pillars
          </FilterTag>
          {PILLARS.map((p) => (
            <FilterTag key={p} pressed={pillar === p} onPress={() => setSearch({ pillar: p })}>
              {PILLAR_NAME[p]}
            </FilterTag>
          ))}
        </span>
        <p className="ff-note">
          {shown.length} of {report.investigations.length} investigations
          {habitat ? `, ordered by their relevance for ${HABITAT_NAME[habitat]}` : ""}. Open one to
          read its summary, scores, profile and sources.
        </p>
      </SectionBlock>
      <SectionBlock>
        <ol className="ff-inv-list">
          {shown.map((inv) => (
            <InvestigationRow
              key={inv.accession}
              inv={inv}
              habitat={habitat}
              isOpen={open === inv.accession}
              onToggle={() => toggle(inv.accession)}
              detail={
                open === inv.accession ? <InvestigationDetail inv={inv} rubric={rubric} /> : null
              }
            />
          ))}
        </ol>
      </SectionBlock>

      <SectionBlock className="ff-sec__head">
        <p className="ff-eyebrow">Same hardware, comparable results</p>
        <p className="ff-note">
          Investigations that share hardware can be compared directly. Each statement names the
          investigations it is about.
        </p>
      </SectionBlock>
      <SectionBlock className="ff-groups">
        {synthesis.hardware_groups.map((group) => (
          <article className="ff-group" key={group.name}>
            <h3 className="ff-group__title">{group.name}</h3>
            <p className="ff-note">{group.hardware}</p>
            <InvestigationRefs accessions={group.accessions} names={names} onOpen={openFromRef} />
            {(
              [
                ["What they share", group.similarities],
                ["How they differ", group.differences],
              ] as const
            ).map(([title, items]) =>
              items.length > 0 ? (
                <div className="ff-group__part" key={title}>
                  <h4 className="ff-eyebrow">{title}</h4>
                  <ul className="ff-inv__list">
                    {items.map((item, i) => (
                      <li key={i}>
                        {item.text}{" "}
                        <InvestigationRefs
                          accessions={item.accessions}
                          names={names}
                          onOpen={openFromRef}
                        />
                      </li>
                    ))}
                  </ul>
                </div>
              ) : null,
            )}
          </article>
        ))}
      </SectionBlock>

      <SectionBlock className="ff-sec__head">
        <p className="ff-eyebrow">What the data does not cover</p>
        <ul className="ff-inv__list ff-gaps">
          {synthesis.gaps.map((gap, i) => (
            <li key={i}>
              {gap.text}{" "}
              <InvestigationRefs accessions={gap.accessions} names={names} onOpen={openFromRef} />
            </li>
          ))}
        </ul>
      </SectionBlock>

      <SectionBlock className="ff-sec__head">
        <p className="ff-eyebrow">Why the Moon raises the stakes</p>
        <div className="ff-facts">
          <Readout label="Moon Base oxygen" value="30" unit="% or more" note="Earth air: 21 %" />
          <Readout
            label="Moon Base pressure"
            value="10.2"
            unit="psi or less"
            note="Earth at sea level: 14.7 psi"
          />
          <Readout label="Spacesuit" value="100" unit="% O₂" note="At only 4.3 psi" />
        </div>
        <p className="ff-note">
          Over 40 % more oxygen than Earth air makes materials much more flammable.
        </p>
      </SectionBlock>
    </>
  );
}

/** One investigation in the ranking: a header that opens its panel. Only one panel is open. */
function InvestigationRow({
  inv,
  habitat,
  isOpen,
  onToggle,
  detail,
}: {
  inv: Investigation;
  habitat: Habitat | undefined;
  isOpen: boolean;
  onToggle: () => void;
  detail: ReactNode;
}) {
  const id = rowId(inv.accession);
  const pillars = PILLARS.filter((p) => inv.pillars[p]);
  return (
    <li className={`ff-inv${isOpen ? " ff-inv--open" : ""}`} id={id}>
      <h3 className="ff-inv__heading">
        <button
          type="button"
          className="ff-inv__toggle"
          aria-expanded={isOpen}
          aria-controls={`${id}-panel`}
          onClick={onToggle}
        >
          <span className="ff-inv__rank" aria-label={`Rank ${inv.rank}`}>
            #{inv.rank}
          </span>
          <span className="ff-inv__name">
            <span className="ff-inv__acronym">{shortName(inv)}</span>
            <span className="ff-inv__title">{inv.title}</span>
          </span>
          <span className="ff-inv__tags">
            {pillars.map((p) => (
              <Tag key={p}>{PILLAR_NAME[p]}</Tag>
            ))}
            {inv.evidence_coverage.card_only ? <Tag variant="gap">PSI card only</Tag> : null}
          </span>
          <span className="ff-inv__numbers">
            {habitat ? (
              <span className="ff-inv__habitat">
                {HABITAT_NAME[habitat]} {inv.habitats[habitat].score} / 3
              </span>
            ) : null}
            <span className="ff-inv__total" aria-label={`Total ${inv.total.toFixed(1)} of 100`}>
              {inv.total.toFixed(1)}
            </span>
          </span>
          <ChevronLeft className="ff-inv__chevron" />
        </button>
      </h3>
      <div id={`${id}-panel`} role="region" aria-label={shortName(inv)} hidden={!isOpen}>
        {detail}
      </div>
    </li>
  );
}
